// One-off generator for content/assets.yaml: a Tabula-drawn plate per discovery, linking to the best
// institutional/scholarly record among its citations; plus the lens schematics and the original plates.
import { writeFileSync } from 'node:fs';
import YAML from 'yaml';
import { loadCorpus } from '../src/lib/content/load';
import { sourceIdOf } from '../src/lib/content/gates';

const c = loadCorpus();
const src = new Map(c.sources.map((s) => [s.id, s]));
const assets: unknown[] = [];
for (const d of c.discoveries) {
  const refs = Object.values(d.claims).flatMap((k) => k.citations.map(sourceIdOf));
  const withUrl = refs.map((r) => src.get(r)!).filter((s) => s?.url);
  const best = withUrl.find((s) => s.scholarly) ?? withUrl[0];
  assets.push({
    id: `plate-${d.id}`,
    title: `Tab. ${d.plate}: ${d.title}`,
    creator: 'Tabula (drawn for this site)',
    date: '2026',
    sourceInstitution: best ? best.author : 'Tabula',
    recordUrl: best?.url ?? 'https://github.com/akhanrepo/anatomy-discovery-coogeee',
    licence: 'CC-BY',
    licenceVerified: true,
    credit: 'Tabula, CC BY 4.0',
    kind: 'generated',
    authenticity: 'ours',
    altText: `Engraved plate of the figure with ${d.structures.join(', ').replace(/-/g, ' ')} inked in, for ${d.displayDate}.`,
  });
}
const lens = (id: string, title: string, url: string, after: string) => ({
  id, title, creator: 'Tabula (schematic)', date: '2026', sourceInstitution: after, recordUrl: url,
  licence: 'CC-BY', licenceVerified: true, credit: `Tabula, CC BY 4.0, after ${after}`, kind: 'generated', authenticity: 'ours',
  altText: `Schematic figure drawn after ${title}, with numbered hotspots for its concepts.`,
});
assets.push(
  lens('lens-islamic-schematic', 'the Tashrīḥ-i Manṣūrī figures', 'https://www.nlm.nih.gov/hmd/arabic/p19.html', 'Mansur ibn Ilyas (NLM copy, 1488)'),
  lens('lens-chinese-schematic', 'the Bronze Man woodcuts', 'https://wellcomecollection.org/works/b7wy9b7s', 'the Bronze Man woodcuts (1537 ed., Wellcome Collection)'),
  lens('lens-ayurveda-schematic', 'the Ayurvedic Man painting', 'https://wellcomecollection.org/works/dfcp3k9d', 'the Ayurvedic Man (Wellcome Collection 574912i)'),
);
const original = (id: string, title: string, creator: string, date: string, inst: string, url: string, kind: string) => ({
  id, title, creator, date, sourceInstitution: inst, recordUrl: url, licence: 'PD', licenceVerified: false,
  credit: inst, kind, authenticity: 'contemporary', altText: `${title}, ${date}.`,
});
assets.push(
  original('tashrih-nlm-1488', 'Tashrīḥ-i Manṣūrī, system figure', 'Mansur ibn Ilyas; copied by Hasan ibn Ahmad', '1488 copy', 'U.S. National Library of Medicine', 'https://www.nlm.nih.gov/hmd/arabic/p19.html', 'manuscript'),
  original('bronze-man-wellcome-1537', 'Bronze Man acupuncture figurine, front view', 'Chinese woodcut', '1537 edition', 'Wellcome Collection', 'https://content.www.wellcomecollection.org/works/xhqf9s5k', 'plate'),
  original('ayurvedic-man-wellcome', 'Ayurvedic Man', 'Unknown Nepalese artists and calligrapher', '18th century', 'Wellcome Collection', 'https://wellcomecollection.org/works/dfcp3k9d', 'plate'),
);
writeFileSync('content/assets.yaml', `# Generated by scripts/gen-assets.ts, then curated by hand. Licence changes need Ali's sign-off (CLAUDE.md).\n${YAML.stringify(assets)}`);
console.log(`wrote ${assets.length} assets`);
